// Explicit developer task only: inspect upstream assets, never run during page loads.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
async function main() {
  const headers = {'User-Agent':'Dexhaven-sprite-verification'};
  async function json(url) { const r=await fetch(url,{headers});if(!r.ok)throw Error(`${r.status} ${url}`);return r.json(); }
  const base='https://api.github.com/repos/PokeAPI/sprites';
  const commit=await json(`${base}/commits/master`), revision=commit.sha;
  const dirs={animated:'black-white/animated',static:'black-white',party:'icons',shinyAnimated:'black-white/animated/shiny',shinyStatic:'black-white/shiny'};
  const folders=await json(`${base}/contents/sprites/pokemon/versions/generation-v?ref=${revision}`);
  const trees={};
  for(const name of ['black-white','icons']){
    const tree=await json(`${base}/git/trees/${folders.find(f=>f.name===name).sha}?recursive=1`);
    if(tree.truncated)throw Error('Upstream tree truncated; cannot verify availability.');
    trees[name]=tree.tree.filter(f=>f.type==='blob').map(f=>`${name}/${f.path}`);
  }
  const available={};
  for(const [kind,dir] of Object.entries(dirs)){
    const extension=kind.toLowerCase().includes('animated')?'gif':'png';
    const matcher=new RegExp(`^${dir}/(\\d+)\\.${extension}$`);
    available[kind]=trees[dir.split('/')[0]].filter(f=>matcher.test(f)).map(f=>Number(f.match(matcher)[1])).filter(id=>id>=1&&id<=649).sort((a,b)=>a-b);
  }
  const samples=[];
  for(const id of [9,151,649])for(const [kind,dir]of Object.entries(dirs).filter(([kind])=>!kind.startsWith('shiny'))){
    const ext=kind==='animated'?'gif':'png',url=`https://raw.githubusercontent.com/PokeAPI/sprites/${revision}/sprites/pokemon/versions/generation-v/${dir}/${id}.${ext}`;
    const r=await fetch(url);if(!r.ok)throw Error(`${r.status} ${url}`);
    const bytes=Buffer.from(await r.arrayBuffer());
    const dest=path.join(root,'tests/fixtures/sprites');fs.mkdirSync(dest,{recursive:true});
    fs.writeFileSync(path.join(dest,`${id}-${kind}.${ext}`),bytes);
    samples.push({id,kind,status:r.status,bytes:bytes.length});
  }
  const manifest={source:'https://github.com/PokeAPI/sprites',revision,verifiedAt:new Date().toISOString(),available,samples};
  fs.writeFileSync(path.join(root,'data/sprite-availability.json'),JSON.stringify(manifest,null,2)+'\n');
  // Browser/Node shared manifest without another runtime fetch.
  fs.writeFileSync(path.join(root,'sprite-availability.js'),`// Generated by scripts/verify-sprites.cjs; see data/sprite-availability.json.\n(() => { const data = ${JSON.stringify({revision,available})}; if(typeof module!=='undefined'&&module.exports)module.exports=data;else globalThis.DexhavenSpriteAssets=data; })();\n`);
  console.log(JSON.stringify({revision,counts:Object.fromEntries(Object.entries(available).map(([k,v])=>[k,v.length])),samples},null,2));
}
main().catch(e=>{console.error(e);process.exitCode=1;});
